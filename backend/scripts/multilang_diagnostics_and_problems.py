from __future__ import annotations

from typing import Any


def _mcq(
    *,
    slug: str,
    language_slug: str,
    domain_slug: str,
    skill_slug: str,
    difficulty: str,
    prompt_en: str,
    prompt_bn: str,
    code_snippet: str,
    options: list[tuple[str, str, str]],
    correct_id: str,
    exp_en: str,
    exp_bn: str,
) -> dict[str, Any]:
    return {
        "slug": slug,
        "language_slug": language_slug,
        "domain_slug": domain_slug,
        "skill_slug": skill_slug,
        "difficulty": difficulty,
        "question_type": "mcq",
        "prompt_en": prompt_en,
        "prompt_bn": prompt_bn,
        "code_snippet": code_snippet,
        "options": [{"id": oid, "text_en": en, "text_bn": bn} for oid, en, bn in options],
        "starter_code": None,
        "correct_option_id": correct_id,
        "explanation_en": exp_en,
        "explanation_bn": exp_bn,
        "evaluation_tests": [],
        "reference_solution": None,
    }


def _code_q(
    *,
    slug: str,
    language_slug: str,
    domain_slug: str,
    skill_slug: str,
    difficulty: str,
    prompt_en: str,
    prompt_bn: str,
    starter_code: str,
    reference_solution: str,
    tests: list[tuple[str, str, str]],
    exp_en: str,
    exp_bn: str,
) -> dict[str, Any]:
    return {
        "slug": slug,
        "language_slug": language_slug,
        "domain_slug": domain_slug,
        "skill_slug": skill_slug,
        "difficulty": difficulty,
        "question_type": "code_execution",
        "prompt_en": prompt_en,
        "prompt_bn": prompt_bn,
        "code_snippet": None,
        "options": [],
        "starter_code": starter_code,
        "correct_option_id": None,
        "explanation_en": exp_en,
        "explanation_bn": exp_bn,
        "evaluation_tests": [
            {"name": name, "input_data": inp, "expected_output": out} for name, inp, out in tests
        ],
        "reference_solution": reference_solution,
    }


